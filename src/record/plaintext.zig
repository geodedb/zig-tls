//! TLS 1.3 Record Plaintext Structures
//!
//! Implements TLSPlaintext and TLSInnerPlaintext formats per RFC 8446 §5.
//!
//! ## RFC Coverage
//! - RFC 8446 §5.1: TLSPlaintext structure and encoding
//! - RFC 8446 §5.4: TLSInnerPlaintext structure (post-decryption)
//!
//! ## Overview
//!
//! **TLSPlaintext** (RFC 8446 §5.1): Outer record framing for TLS 1.3.
//! Used for the record layer header when transmitting fragments.
//!
//! **TLSInnerPlaintext** (RFC 8446 §5.4): Inner structure after AEAD decryption.
//! Contains actual content plus a trailing content type byte and optional padding.
//!
//! ## QUIC Context
//!
//! In QUIC, the traditional TLS record layer is replaced by CRYPTO frames,
//! but these plaintext structures are still used for:
//! - Testing and validation of TLS 1.3 compatibility
//! - Understanding the inner format of AEAD-protected content
//! - Reference implementation for conformance testing
//!
//! ## Security Notes
//!
//! - Fragment length validation prevents buffer overruns
//! - Padding provides traffic analysis resistance (RFC 8446 §5.4)
//! - Content type embedded inside encryption boundary (TLSInnerPlaintext)

const std = @import("std");

/// Legacy protocol versions carried in TLS record headers.
///
/// RFC 8446 §5.1 mandates that TLS 1.3 records MUST use legacy_record_version
/// = 0x0303 (TLS 1.2) for compatibility with middleboxes. Actual version
/// negotiation happens in the handshake, not the record layer.
///
/// ## RFC Reference
/// RFC 8446 §5.1 - Record Layer: "legacy_record_version: MUST be set to 0x0303
/// for all records generated by a TLS 1.3 implementation"
pub const LegacyVersion = enum(u16) {
    ssl_3_0 = 0x0300,
    tls_1_0 = 0x0301,
    tls_1_1 = 0x0302,
    tls_1_2 = 0x0303,
};

/// Default legacy version for TLS 1.3 records (0x0303 = TLS 1.2).
///
/// TLS 1.3 fixes the outer record version to 0x0303 for backward compatibility.
/// This prevents middlebox interference while negotiating TLS 1.3 in the handshake.
///
/// ## RFC Reference
/// RFC 8446 §5.1 - All TLS 1.3 implementations must use 0x0303
pub const default_legacy_version = LegacyVersion.tls_1_2;

/// TLS record content types identifying the higher-level protocol.
///
/// Defined in RFC 8446 §5.1. In TLS 1.3, encrypted records use
/// content_type = application_data (23) and embed the real content type
/// in the TLSInnerPlaintext structure after decryption.
///
/// ## RFC Reference
/// RFC 8446 §5.1 - ContentType enum values
/// RFC 8446 §5.4 - TLSInnerPlaintext carries true content type after decryption
pub const ContentType = enum(u8) {
    invalid = 0,
    change_cipher_spec = 20, // RFC 8446 §5 - CCS is deprecated in TLS 1.3
    alert = 21,
    handshake = 22,
    application_data = 23,
    heartbeat = 24, // RFC 6520 - Optional extension
};

/// Maximum TLSPlaintext fragment length (2^14 bytes).
///
/// RFC 8446 §5.1 specifies that TLS record fragments MUST NOT exceed 2^14 bytes.
/// Implementations receiving larger fragments must terminate the connection with
/// a record_overflow alert.
///
/// ## RFC Reference
/// RFC 8446 §5.1 - "The length MUST NOT exceed 2^14 bytes"
pub const max_plaintext_fragment = 16384; // 2^14 bytes

/// Maximum padding length for TLSInnerPlaintext.
///
/// RFC 8446 allows padding up to 2^14 bytes to obscure content length.
/// We enforce the same bound as plaintext fragments for validation consistency.
///
/// ## RFC Reference
/// RFC 8446 §5.4 - TLSInnerPlaintext.zeros can be arbitrary length
pub const max_inner_padding = max_plaintext_fragment;

/// Errors that can occur during TLS record plaintext processing and AEAD operations.
///
/// Covers record framing errors (RFC 8446 §5.1, §5.4) and AEAD errors (RFC 8446 §5.2, §5.5).
pub const RecordError = error{
    /// Record fragment exceeds 2^14 bytes (RFC 8446 §5.1)
    FragmentTooLarge,
    /// Record header is incomplete (less than 5 bytes)
    RecordTooShort,
    /// Declared length doesn't match actual data length
    LengthMismatch,
    /// ContentType value is not recognized (RFC 8446 §5.1)
    InvalidContentType,
    /// TLSInnerPlaintext has no content type byte (RFC 8446 §5.4)
    MissingContentType,
    /// Padding exceeds maximum allowed length
    PaddingTooLarge,
    /// Legacy version is not a known TLS version
    UnsupportedLegacyVersion,
    /// AEAD key length doesn't match cipher suite requirements
    InvalidKeyLength,
    /// AEAD IV length is invalid (must be 8-12 bytes)
    InvalidIvLength,
    /// Ciphertext is shorter than AEAD tag length
    CiphertextTooShort,
    /// AEAD authentication tag verification failed (RFC 5116)
    AuthenticationFailed,
    /// AEAD usage limit reached (RFC 8446 §5.5)
    AeadLimitExceeded,
    /// Caller-provided buffer is too small for the output
    BufferTooSmall,
    /// Memory allocation failed
    OutOfMemory,
    /// Cipher suite is not permitted under the active backend (e.g.
    /// ChaCha20-Poly1305 is forbidden under -Dfips=true; FIPS-140-3
    /// allows only AES-GCM record protection).
    UnsupportedCipherSuite,
};

/// Lightweight view over a TLSPlaintext record (RFC 8446 §5.1).
///
/// Provides zero-copy access to a parsed TLS record without owning the
/// underlying buffer. The fragment slice references the original data.
///
/// ## RFC Reference
/// RFC 8446 §5.1 - TLSPlaintext structure:
/// ```
/// struct {
///     ContentType type;
///     ProtocolVersion legacy_record_version;
///     uint16 length;
///     opaque fragment[TLSPlaintext.length];
/// } TLSPlaintext;
/// ```
pub const PlaintextView = struct {
    content_type: ContentType,
    legacy_version: LegacyVersion,
    fragment: []const u8,
};

/// Encode a TLSPlaintext record from content type and fragment data.
///
/// Creates a complete TLS record with 5-byte header followed by the fragment.
/// The header format follows RFC 8446 §5.1:
///
/// ```
/// struct {
///     ContentType type;                    // 1 byte
///     ProtocolVersion legacy_record_version; // 2 bytes (always 0x0303)
///     uint16 length;                       // 2 bytes (big-endian)
///     opaque fragment[TLSPlaintext.length];
/// } TLSPlaintext;
/// ```
///
/// ## Parameters
/// - `allocator`: Memory allocator for the output buffer
/// - `content_type`: Record content type (handshake, alert, application_data, etc.)
/// - `fragment`: Payload data to encode (must not exceed 2^14 bytes)
///
/// ## Returns
/// Newly allocated buffer containing the complete TLS record. Caller owns the buffer.
///
/// ## Errors
/// - `FragmentTooLarge`: Fragment exceeds max_plaintext_fragment (2^14 bytes)
/// - `OutOfMemory`: Allocation failed
///
/// ## RFC References
/// - RFC 8446 §5.1 - TLSPlaintext structure and encoding
/// - RFC 8446 §5.1 - legacy_record_version must be 0x0303 for TLS 1.3
pub fn encodePlaintext(allocator: std.mem.Allocator, content_type: ContentType, fragment: []const u8) ![]u8 {
    // RFC 8446 §5.1 - Fragment length must not exceed 2^14 bytes
    if (fragment.len > max_plaintext_fragment) return RecordError.FragmentTooLarge;
    const header_len: usize = 5;
    var out = try allocator.alloc(u8, header_len + fragment.len);
    // RFC 8446 §5.1 - ContentType byte
    out[0] = @intFromEnum(content_type);
    // RFC 8446 §5.1 - legacy_record_version MUST be 0x0303 (TLS 1.2)
    out[1] = 0x03;
    out[2] = 0x03;
    // RFC 8446 §5.1 - Length field in big-endian format
    const length: u16 = @intCast(fragment.len);
    out[3] = @intCast(length >> 8);
    out[4] = @intCast(length & 0xff);
    // RFC 8446 §5.1 - Fragment payload
    @memcpy(out[header_len..], fragment);
    return out;
}

/// Decode a TLSPlaintext record from wire format.
///
/// Parses the 5-byte TLS record header and validates the structure. Returns
/// a zero-copy view that references the original buffer. Does NOT allocate.
///
/// ## Parameters
/// - `data`: Complete TLS record buffer (header + fragment)
///
/// ## Returns
/// PlaintextView with parsed header fields and fragment slice (borrowed from `data`)
///
/// ## Errors
/// - `RecordTooShort`: Buffer has less than 5 bytes (incomplete header)
/// - `LengthMismatch`: Declared length doesn't match actual buffer size
/// - `InvalidContentType`: ContentType byte is not recognized
/// - `UnsupportedLegacyVersion`: Legacy version is not a known TLS version
///
/// ## RFC References
/// - RFC 8446 §5.1 - TLSPlaintext structure and parsing
/// - RFC 8446 §5.1 - Length field validation and fragment extraction
///
/// ## Security Considerations
/// This function validates length consistency to prevent buffer overruns
/// when processing the fragment field.
pub fn decodePlaintext(data: []const u8) RecordError!PlaintextView {
    // RFC 8446 §5.1 - TLSPlaintext header is 5 bytes minimum
    if (data.len < 5) return RecordError.RecordTooShort;
    // RFC 8446 §5.1 - Parse big-endian uint16 length field
    const declared_len = (@as(u16, data[3]) << 8) | @as(u16, data[4]);
    const total_len: usize = 5 + declared_len;
    // RFC 8446 §5.1 - Validate declared length matches actual data
    if (data.len != total_len) return RecordError.LengthMismatch;
    // RFC 8446 §5.1 - Parse ContentType and legacy_record_version
    const ct = try parseContentType(data[0]);
    const version = try parseLegacyVersion(data[1], data[2]);
    // RFC 8446 §5.1 - Extract fragment (zero-copy slice)
    const fragment = data[5..total_len];
    return PlaintextView{
        .content_type = ct,
        .legacy_version = version,
        .fragment = fragment,
    };
}

/// Unpacked TLSInnerPlaintext structure (RFC 8446 §5.4).
///
/// After decrypting a TLS 1.3 record, the plaintext has this structure:
///
/// ```
/// struct {
///     opaque content[TLSPlaintext.length];
///     ContentType type;
///     uint8 zeros[length_of_padding];
/// } TLSInnerPlaintext;
/// ```
///
/// The true content type is embedded at the end of the plaintext, followed
/// by optional zero-byte padding for traffic analysis protection.
///
/// ## RFC Reference
/// RFC 8446 §5.4 - Record Payload Protection structure
pub const InnerPlaintext = struct {
    content_type: ContentType,
    content: []const u8,
    padding_len: usize,
};

/// Pack content and padding into TLSInnerPlaintext wire format.
///
/// Constructs the structure used inside AEAD-protected TLS 1.3 records:
/// content || content_type || zeros[padding_len]
///
/// The content type byte is appended after the content, followed by zero
/// padding if requested. This allows receivers to strip padding by scanning
/// backwards from the end.
///
/// ## Parameters
/// - `allocator`: Memory allocator for the output buffer
/// - `content_type`: True content type (handshake, application_data, alert)
/// - `content`: Payload data to pack
/// - `padding_len`: Number of zero bytes to append (for traffic analysis resistance)
///
/// ## Returns
/// Newly allocated TLSInnerPlaintext buffer. Caller owns the buffer.
///
/// ## Errors
/// - `PaddingTooLarge`: Padding exceeds max_inner_padding
/// - `FragmentTooLarge`: Total length exceeds max_plaintext_fragment
/// - `InvalidContentType`: content_type is .invalid
/// - `OutOfMemory`: Allocation failed
///
/// ## RFC References
/// - RFC 8446 §5.4 - TLSInnerPlaintext structure
/// - RFC 8446 §5.4 - Padding for traffic analysis resistance
pub fn packInnerPlaintext(allocator: std.mem.Allocator, content_type: ContentType, content: []const u8, padding_len: usize) ![]u8 {
    // RFC 8446 §5.4 - Validate padding length
    if (padding_len > max_inner_padding) return RecordError.PaddingTooLarge;
    // RFC 8446 §5.1 - Total cannot exceed record fragment limit
    if (content.len + 1 + padding_len > max_plaintext_fragment) return RecordError.FragmentTooLarge;
    // RFC 8446 §5.4 - ContentType must be valid
    if (content_type == .invalid) return RecordError.InvalidContentType;

    const total_len = content.len + 1 + padding_len;
    var out = try allocator.alloc(u8, total_len);
    // RFC 8446 §5.4 - Content bytes
    @memcpy(out[0..content.len], content);
    // RFC 8446 §5.4 - ContentType byte at end of content
    out[content.len] = @intFromEnum(content_type);
    // RFC 8446 §5.4 - Zero padding for traffic analysis resistance
    if (padding_len > 0) {
        @memset(out[content.len + 1 ..], 0);
    }
    return out;
}

/// Unpack a TLSInnerPlaintext buffer to extract content, type, and padding.
///
/// Parses the TLSInnerPlaintext structure by scanning backwards from the end
/// to strip zero padding and locate the content type byte. Returns a zero-copy
/// view that references the original buffer.
///
/// ## Parameters
/// - `buffer`: TLSInnerPlaintext buffer (typically from AEAD decryption)
///
/// ## Returns
/// InnerPlaintext with content slice, content type, and padding count
///
/// ## Errors
/// - `MissingContentType`: Buffer is empty or all zeros (no content type found)
/// - `InvalidContentType`: Content type byte is not recognized
///
/// ## RFC References
/// - RFC 8446 §5.4 - TLSInnerPlaintext structure and parsing
/// - RFC 8446 §5.4 - "Padding removal: scan backwards to find non-zero byte"
///
/// ## Algorithm
/// 1. Scan backwards from end while bytes are 0x00 (padding)
/// 2. Next byte is the ContentType
/// 3. Remaining bytes are the content
pub fn unpackInnerPlaintext(buffer: []const u8) RecordError!InnerPlaintext {
    // RFC 8446 §5.4 - Buffer must contain at least a content type byte
    if (buffer.len == 0) return RecordError.MissingContentType;

    // RFC 8446 §5.4 - Scan backwards to strip zero padding
    var idx = buffer.len;
    var pad: usize = 0;
    while (idx > 0 and buffer[idx - 1] == 0) : (idx -= 1) {
        pad += 1;
    }
    // RFC 8446 §5.4 - Must find at least one non-zero byte (the content type)
    if (idx == 0) return RecordError.MissingContentType;
    // RFC 8446 §5.4 - Last non-zero byte is the ContentType
    const ct_byte = buffer[idx - 1];
    const ct = try parseContentType(ct_byte);
    // RFC 8446 §5.4 - Everything before content type is the actual content
    const content = buffer[0 .. idx - 1];
    return InnerPlaintext{
        .content_type = ct,
        .content = content,
        .padding_len = pad,
    };
}

/// Parse ContentType byte value (RFC 8446 §5.1).
///
/// Used internally by decodePlaintext and unpackInnerPlaintext.
/// Public for testing purposes.
pub fn parseContentType(byte: u8) RecordError!ContentType {
    return switch (byte) {
        @intFromEnum(ContentType.change_cipher_spec) => .change_cipher_spec,
        @intFromEnum(ContentType.alert) => .alert,
        @intFromEnum(ContentType.handshake) => .handshake,
        @intFromEnum(ContentType.application_data) => .application_data,
        @intFromEnum(ContentType.heartbeat) => .heartbeat,
        else => RecordError.InvalidContentType,
    };
}

/// Parse legacy version from two bytes (RFC 8446 §5.1).
///
/// Used internally by decodePlaintext.
/// Public for testing purposes.
pub fn parseLegacyVersion(hi: u8, lo: u8) RecordError!LegacyVersion {
    const value: u16 = (@as(u16, hi) << 8) | @as(u16, lo);
    return switch (value) {
        @intFromEnum(LegacyVersion.ssl_3_0) => .ssl_3_0,
        @intFromEnum(LegacyVersion.tls_1_0) => .tls_1_0,
        @intFromEnum(LegacyVersion.tls_1_1) => .tls_1_1,
        @intFromEnum(LegacyVersion.tls_1_2) => .tls_1_2,
        else => RecordError.UnsupportedLegacyVersion,
    };
}
