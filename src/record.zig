    defer cipher.wipe();

    const plaintext = "test";
    const aad = "";

    // Encrypt 5 times (should succeed)
    var i: u64 = 0;
    while (i < 5) : (i += 1) {
        const ct = try cipher.seal(allocator, i, aad, plaintext);
